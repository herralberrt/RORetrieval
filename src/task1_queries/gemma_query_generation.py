def category_to_type(category: str) -> str:
    """Map a category directory name to a document type."""
    category = category.lower()
    if category in NEWS_CATEGORIES:
        return "news"
    if category in ("recipes", "stories", "summarization"):
        return category
    return "unknown"


def document_text(doc: Dict[str, Any], doc_type: str, max_chars: int) -> str:
    """Build the text block shown to the model for one document."""
    title = (doc.get("title") or "").strip()
    parts: List[str] = []

    if title:
        parts.append(f"Titlu: {title}")

    if doc_type == "recipes":
        ingredients = (doc.get("ingredients") or "").strip()
        if ingredients:
            parts.append(f"Ingrediente: {ingredients}")
        body = (doc.get("content") or "").strip()
    elif doc_type == "stories":
        author = (doc.get("author") or "").strip()
        if author and author.lower() != "unknown":
            parts.append(f"Autor: {author}")
        body = (doc.get("content") or "").strip()
    else:
        body = (doc.get("text") or doc.get("content") or "").strip()
        if not body:
            body = (doc.get("summary") or "").strip()

    if body:
        parts.append(f"Text: {body}")

    text = "\n".join(parts).strip()
    if len(text) > max_chars:
        text = text[:max_chars].rsplit(" ", 1)[0] + " […]"
    return text


def _is_lfs_pointer(filepath: str) -> bool:
    """True for a git-lfs pointer file that was never fetched (`git lfs pull`)."""
    try:
        with open(filepath, "r", encoding="utf-8", errors="ignore") as f:
            return f.readline().startswith("version https://git-lfs")
    except OSError:
        return False


def usable_categories(
    categories_dir: str,
    categories: Optional[List[str]] = None,
    include_aggregates: bool = False,
    verbose: bool = True,
) -> List[str]:
    """Category directories to read, in a stable order.

    An explicit --categories selection always wins, so `--categories news`
    still works when the aggregate is what you actually want.
    """
    if not os.path.isdir(categories_dir):
        raise FileNotFoundError(f"Categories directory not found: {categories_dir}")

    wanted = {c.lower() for c in categories} if categories else None
    selected = []

    for category in sorted(os.listdir(categories_dir)):
        if not os.path.isdir(os.path.join(categories_dir, category)):
            continue
        if category_to_type(category) == "unknown":
            if verbose:
                print(f"  ⚠ Skipping unknown category: {category}")
            continue
        if wanted is not None:
            if category.lower() in wanted:
                selected.append(category)
            continue
        if category.lower() in AGGREGATE_CATEGORIES and not include_aggregates:
            if verbose:
                print(f"  ▸ Skipping aggregate category '{category}' "
                      f"(duplicates the per-outlet directories; "
                      f"--include-aggregates to keep it)")
            continue
        selected.append(category)

    return selected


def iter_documents(
    categories_dir: str,
    categories: Optional[List[str]] = None,
    per_category: Optional[int] = None,
    stride: int = 1,
    include_aggregates: bool = False,
) -> Iterator[Tuple[Dict[str, Any], str]]:
    """Stream (document, doc_type) pairs from the category JSONL files."""
    for category in usable_categories(categories_dir, categories, include_aggregates):
        category_path = os.path.join(categories_dir, category)
        doc_type = category_to_type(category)

        emitted = 0
        for filename in sorted(os.listdir(category_path)):
            if not filename.endswith(".jsonl"):
                continue
            filepath = os.path.join(category_path, filename)
            if _is_lfs_pointer(filepath):
                print(f"  ⚠ {filepath} is an unfetched git-lfs pointer - run `git lfs pull`")
                continue

            with open(filepath, "r", encoding="utf-8") as f:
                for index, line in enumerate(f):
                    if per_category is not None and emitted >= per_category:
                        break
                    if not line.strip():
                        continue
                    if index % stride != 0:
                        continue
                    try:
                        doc = json.loads(line)
                    except json.JSONDecodeError:
                        continue
                    doc.setdefault("category", category)
                    yield doc, doc_type
                    emitted += 1

            if per_category is not None and emitted >= per_category:
                break


def count_categories(
    categories_dir: str,
    categories: Optional[List[str]],
    include_aggregates: bool = False,
) -> int:
    """Number of category directories that will be read (for balanced sampling)."""
    return len(usable_categories(categories_dir, categories, include_aggregates,
                                verbose=False))



class VLLMBackend:
    """Batched generation with vLLM (continuous batching)."""

    name = "vllm"

    def __init__(self, args):
        from transformers import AutoTokenizer
        from vllm import LLM, SamplingParams

        print(f"▸ Loading {args.model} with vLLM …")
        self.tokenizer = AutoTokenizer.from_pretrained(args.model)
        self.llm = LLM(
            model=args.model,
            dtype=args.dtype,
            max_model_len=args.max_model_len,
            gpu_memory_utilization=args.gpu_memory_utilization,
            tensor_parallel_size=args.tensor_parallel_size,
            seed=args.seed,
            trust_remote_code=True,
        )
        self.sampling_params = SamplingParams(
            temperature=args.temperature,
            top_p=args.top_p,
            max_tokens=args.max_new_tokens,
            seed=args.seed,
        )

    def _to_token_ids(self, prompt: str) -> List[int]:
        # Single user turn: Gemma chat templates do not accept a system role.
        # Tokenize here rather than handing vLLM a string: the chat template
        # already emits <bos>, and vLLM would prepend a second one.
        return self.tokenizer.apply_chat_template(
            [{"role": "user", "content": prompt}],
            tokenize=True,
            add_generation_prompt=True,
        )

    def generate(self, prompts: List[str]) -> List[str]:
        requests = [{"prompt_token_ids": self._to_token_ids(p)} for p in prompts]
        outputs = self.llm.generate(requests, self.sampling_params, use_tqdm=False)
        return [o.outputs[0].text for o in outputs]


class TransformersBackend:
    """Plain HF `generate`, for debugging or when vLLM is unavailable."""

    name = "transformers"

    def __init__(self, args):
        import torch
        from transformers import AutoTokenizer

        print(f"▸ Loading {args.model} with transformers …")
        self.torch = torch
        self.tokenizer = AutoTokenizer.from_pretrained(args.model, padding_side="left")
        if self.tokenizer.pad_token is None:
            self.tokenizer.pad_token = self.tokenizer.eos_token

        dtype = {
            "bfloat16": torch.bfloat16,
            "float16": torch.float16,
            "float32": torch.float32,
        }.get(args.dtype, "auto")

        self.model = self._load_model(args.model, dtype)
        self.model.eval()
        self.args = args

    @staticmethod
    def _load_model(model_name: str, dtype):
        """Gemma 3 4b+ ships as a multimodal checkpoint; 1b is text-only."""
        import transformers

        errors = []
        for cls_name in ("AutoModelForCausalLM", "AutoModelForImageTextToText"):
            cls = getattr(transformers, cls_name, None)
            if cls is None:
                continue
            try:
                return cls.from_pretrained(model_name, torch_dtype=dtype, device_map="auto")
            except (ValueError, KeyError, OSError) as exc:
                errors.append(f"{cls_name}: {exc}")
        raise RuntimeError("Could not load model. Tried:\n  " + "\n  ".join(errors))

    def generate(self, prompts: List[str]) -> List[str]:
        chats = [
            self.tokenizer.apply_chat_template(
                [{"role": "user", "content": p}],
                tokenize=False,
                add_generation_prompt=True,
            )
            for p in prompts
        ]
        inputs = self.tokenizer(
            chats,
            return_tensors="pt",
            padding=True,
            truncation=True,
            max_length=self.args.max_model_len - self.args.max_new_tokens,
            add_special_tokens=False,
        ).to(self.model.device)

        with self.torch.inference_mode():
            outputs = self.model.generate(
                **inputs,
                max_new_tokens=self.args.max_new_tokens,
                do_sample=self.args.temperature > 0,
                temperature=self.args.temperature,
                top_p=self.args.top_p,
                pad_token_id=self.tokenizer.pad_token_id,
            )

        generated = outputs[:, inputs["input_ids"].shape[1]:]
        return self.tokenizer.batch_decode(generated, skip_special_tokens=True)


def build_backend(args):
    """Instantiate the requested backend, falling back to transformers."""
    if args.backend == "none":
        return None
    if args.backend in ("vllm", "auto"):
        try:
            return VLLMBackend(args)
        except Exception as exc:
            if args.backend == "vllm":
                raise
            print(f"⚠ vLLM unavailable ({exc}); falling back to transformers.")
    return TransformersBackend(args)



def load_done_ids(output_path: str) -> set:
    """Doc ids already present in a previous (possibly interrupted) run."""
    done = set()
    if not os.path.exists(output_path):
        return done
    with open(output_path, "r", encoding="utf-8") as f:
        for line in f:
            if not line.strip():
                continue
            try:
                done.add(json.loads(line).get("doc_id"))
            except json.JSONDecodeError:
                continue
    done.discard(None)
    return done


def print_stats(stats: Dict[str, Dict[str, Any]], elapsed: float, docs_done: int) -> None:
    print("\n" + "=" * 70)
    print("GEMMA QUERY GENERATION - FINAL REPORT")
    print("=" * 70)

    print("\n📊 QUERIES GENERATED BY TYPE:")
    total = 0
    for doc_type in sorted(stats):
        count = stats[doc_type]["count"]
        total += count
        print(f"  {doc_type:<20} {count:>8} queries  ({stats[doc_type]['docs']} docs)")
    print(f"  {'─' * 30}")
    print(f"  {'TOTAL':<20} {total:>8} queries")

    print("\n📈 QUALITY METRICS BY TYPE:")
    for doc_type in sorted(stats):
        scores = stats[doc_type]["quality_scores"]
        if scores:
            print(
                f"  {doc_type:<20} avg={mean(scores):.3f} ± {std(scores):.3f} "
                f"(min={min(scores):.2f}, max={max(scores):.2f})"
            )

    rate = docs_done / elapsed if elapsed > 0 else 0.0
    print(f"\n⏱  {docs_done} documents in {timedelta(seconds=int(elapsed))} "
          f"({rate:.2f} docs/s, {rate * 3600:.0f} docs/h)")
    print("=" * 70)


def run(args) -> None:
    output_path = args.output
    os.makedirs(os.path.dirname(output_path) or ".", exist_ok=True)

    done_ids = load_done_ids(output_path) if args.resume else set()
    if args.resume and done_ids:
        print(f"▸ Resuming: {len(done_ids)} documents already generated.")
    elif not args.resume and os.path.exists(output_path):
        print(f"▸ Overwriting existing {output_path} (use --resume to continue instead).")
        open(output_path, "w", encoding="utf-8").close()

    per_category = args.per_category
    if per_category is None and args.max_docs:
        n_cats = count_categories(args.categories_dir, args.categories,
                                  args.include_aggregates)
        if n_cats:
            per_category = -(-args.max_docs // n_cats)  # ceil, balanced sampling
            print(f"▸ Balanced sampling: {per_category} documents from each of {n_cats} categories.")

    metrics = FastQueryMetrics()
    stats: Dict[str, Dict[str, Any]] = {}
    backend = build_backend(args)

    deadline = time.monotonic() + args.time_budget_min * 60 if args.time_budget_min > 0 else None
    started = time.monotonic()
    docs_done = 0
    written = 0
    skipped_short = 0
    skipped_unparsed = 0
    budget_hit = False

    documents = iter_documents(
        args.categories_dir,
        categories=args.categories,
        per_category=per_category,
        stride=args.stride,
        include_aggregates=args.include_aggregates,
    )

    batch_docs: List[Tuple[Dict[str, Any], str]] = []
    batch_prompts: List[str] = []

    progress = tqdm(total=args.max_docs or None, desc="Generating", unit="doc")
    out_file = open(output_path, "a", encoding="utf-8")

    def flush_batch() -> None:
        nonlocal written, skipped_unparsed, docs_done

        if not batch_prompts:
            return

        if backend is None:  # --dry-run
            raw_outputs = ["[]"] * len(batch_prompts)
        else:
            raw_outputs = backend.generate(batch_prompts)

        for (doc, doc_type), raw in zip(batch_docs, raw_outputs):
            queries = parse_queries(raw, args.queries_per_doc)
            record_metrics = metrics.score_record(queries, doc) if queries else {}

            if queries and args.min_quality > 0:
                keep = [
                    q for q, s in zip(queries, record_metrics["quality_scores"])
                    if s >= args.min_quality
                ]
                if len(keep) != len(queries):
                    queries = keep
                    record_metrics = metrics.score_record(queries, doc) if queries else {}

            if not queries:
                skipped_unparsed += 1

            record = {
                "doc_id": doc.get("doc_id", ""),
                "source": doc.get("source", ""),
                "category": doc.get("category", ""),
                "type": doc_type,
                "title": doc.get("title", ""),
                "queries": queries,
                "num_queries": len(queries),
                "metrics": record_metrics,
                "generator": args.model,
            }
            out_file.write(json.dumps(record, ensure_ascii=False) + "\n")
            written += 1

            bucket = stats.setdefault(doc_type, {"count": 0, "docs": 0, "quality_scores": []})
            bucket["count"] += len(queries)
            bucket["docs"] += 1
            bucket["quality_scores"].extend(record_metrics.get("quality_scores", []))

        out_file.flush()
        docs_done += len(batch_docs)
        batch_docs.clear()
        batch_prompts.clear()

    try:
        for doc, doc_type in documents:
            if args.max_docs and docs_done + len(batch_docs) >= args.max_docs:
                break
            if deadline and time.monotonic() >= deadline:
                budget_hit = True
                break

            doc_id = doc.get("doc_id", "")
            if doc_id in done_ids:
                continue

            prompt = build_prompt(doc, doc_type, args.queries_per_doc, args.max_doc_chars)
            if prompt is None:
                skipped_short += 1
                continue

            if args.dry_run:
                print("\n" + "─" * 70)
                print(f"[{doc_type}] {doc_id}")
                print("─" * 70)
                print(prompt)
                docs_done += 1
                if args.max_docs and docs_done >= args.max_docs:
                    break
                continue

            batch_docs.append((doc, doc_type))
            batch_prompts.append(prompt)

            if len(batch_prompts) >= args.batch_size:
                flush_batch()
                progress.update(args.batch_size)

        if not args.dry_run:
            flush_batch()
    except KeyboardInterrupt:
        print("\n⚠ Interrupted - flushing what has been generated so far.")
        if not args.dry_run:
            flush_batch()
    finally:
        out_file.close()
        if hasattr(progress, "close"):
            progress.close()

    if args.dry_run:
        print(f"\n✓ Dry run: built prompts for {docs_done} documents (no model loaded).")
        return

    elapsed = time.monotonic() - started
    print(f"\n✓ Wrote {written} records to {output_path}")
    if skipped_short:
        print(f"  ({skipped_short} documents skipped: text too short)")
    if skipped_unparsed:
        print(f"  ({skipped_unparsed} documents produced no usable query)")
    if budget_hit:
        print(f"  ⏳ Time budget of {args.time_budget_min} min reached - "
              f"rerun with --resume to continue.")

    print_stats(stats, elapsed, docs_done)

    stats_path = output_path + ".stats.json"
    with open(stats_path, "w", encoding="utf-8") as f:
        json.dump(
            {
                "config": vars(args),
                "elapsed_seconds": round(elapsed, 1),
                "documents": docs_done,
                "records_written": written,
                "budget_reached": budget_hit,
                "by_type": {
                    t: {
                        "docs": s["docs"],
                        "queries": s["count"],
                        "avg_quality": round(mean(s["quality_scores"]), 4),
                        "std_quality": round(std(s["quality_scores"]), 4),
                    }
                    for t, s in stats.items()
                },
            },
            f,
            indent=2,
            ensure_ascii=False,
        )
    print(f"✓ Run manifest: {stats_path}")


def parse_args(argv=None):
    parser = argparse.ArgumentParser(
        description="Generate Romanian retrieval queries from documents with Gemma 3.",
        formatter_class=argparse.ArgumentDefaultsHelpFormatter,
    )

    model_group = parser.add_argument_group("model")
    model_group.add_argument("--model", default=os.environ.get("GEMMA_MODEL", DEFAULT_MODEL),
                             help="HuggingFace model id (gated: accept the Gemma license first)")
    model_group.add_argument("--backend", default=os.environ.get("QGEN_BACKEND", "auto"),
                             choices=["auto", "vllm", "transformers", "none"])
    model_group.add_argument("--dtype", default="bfloat16",
                             choices=["auto", "bfloat16", "float16", "float32"],
                             help="use float16 on GPUs without bf16 support (e.g. V100)")
    model_group.add_argument("--max-model-len", type=int, default=2048)
    model_group.add_argument("--max-new-tokens", type=int, default=192)
    model_group.add_argument("--temperature", type=float, default=0.8)
    model_group.add_argument("--top-p", type=float, default=0.95)
    model_group.add_argument("--gpu-memory-utilization", type=float, default=0.90)
    model_group.add_argument("--tensor-parallel-size", type=int, default=1)
    model_group.add_argument("--seed", type=int, default=42)

    data_group = parser.add_argument_group("data")
    data_group.add_argument("--categories-dir", default=DEFAULT_CATEGORIES_DIR)
    data_group.add_argument("--categories", nargs="+", default=None,
                            help="only these category directories (default: all)")
    data_group.add_argument("--output", default=os.environ.get("QGEN_OUTPUT", DEFAULT_OUTPUT))
    data_group.add_argument("--max-docs", type=int, default=20000,
                            help="total document budget (0 = no limit)")
    data_group.add_argument("--per-category", type=int, default=None,
                            help="per-category cap (default: max-docs split evenly)")
    data_group.add_argument("--stride", type=int, default=1,
                            help="take every Nth document for a spread-out sample")
    data_group.add_argument("--include-aggregates", action="store_true",
                            help="also read data/categories/news/, which duplicates "
                                 "the ten per-outlet directories")
    data_group.add_argument("--max-doc-chars", type=int, default=2000)

    run_group = parser.add_argument_group("run")
    run_group.add_argument("--queries-per-doc", type=int, default=4)
    run_group.add_argument("--batch-size", type=int, default=256,
                           help="use ~8 for the transformers backend")
    run_group.add_argument("--min-quality", type=float, default=0.0,
                           help="drop queries below this heuristic quality score")
    run_group.add_argument("--time-budget-min", type=float,
                           default=float(os.environ.get("QGEN_TIME_BUDGET_MIN", 110)),
                           help="stop cleanly after this many minutes (0 = unlimited)")
    run_group.add_argument("--resume", action="store_true",
                           help="append to the output file, skipping documents already done")
    run_group.add_argument("--dry-run", action="store_true",
                           help="print prompts without loading a model")

    args = parser.parse_args(argv)
    if args.dry_run:
        args.backend = "none"
        if args.max_docs == 20000:
            args.max_docs = 3
    if args.backend == "transformers" and args.batch_size > 32:
        print("▸ Lowering batch size to 8 for the transformers backend.")
        args.batch_size = 8
    return args


def main(argv=None) -> None:
    args = parse_args(argv)

    print("\n" + "=" * 70)
    print("TASK 1: QUERY GENERATION WITH GEMMA 3")
    print("=" * 70)
    print(f"  model        : {args.model}")
    print(f"  backend      : {args.backend}")
    print(f"  output       : {args.output}")
    print(f"  doc budget   : {args.max_docs or 'all'}")
    print(f"  time budget  : {args.time_budget_min or 'unlimited'} min")
    print(f"  queries/doc  : {args.queries_per_doc}")

    run(args)


if __name__ == "__main__":
    main()

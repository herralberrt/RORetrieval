"""
TASK 1: Query Generation with Gemma 3

Replaces the old template-based generator: instead of filling `{topic}` into
a handful of Romanian patterns, each query is generated by an instruction-tuned
Gemma 3 model that actually reads the document text.

Backends:
  - vllm         : batched, continuous-batching inference (default, fast)
  - transformers : plain HF generate (fallback / debugging / small runs)
  - none         : no model loaded, only prompt building (`--dry-run`)

The output schema is unchanged, so `analyze_query_metrics.py` and the task2
triplet scripts keep working:

    {"doc_id", "source", "type", "title", "queries", "num_queries", "metrics", ...}

The run is wall-clock bounded (`--time-budget-min`) and resumable
(`--resume`), so it fits inside a 2-hour SLURM allocation: whatever is
generated before the budget expires is already flushed to disk, and a second
job continues from where the first stopped.

Usage:
    python3 -m src.task1_queries.gemma_query_generation --help
    python3 -m src.task1_queries.gemma_query_generation --dry-run --max-docs 3
    python3 -m src.task1_queries.gemma_query_generation --max-docs 20000
"""


BANNED_PATTERNS = [
    r"acest (articol|text|document|fragment)",
    r"textul de mai sus",
    r"\bîn document\b",
    r"documentul de mai sus",
    r"pasajul de mai sus",
]

_JSON_ARRAY = re.compile(r"\[.*?\]", re.DOTALL)
_LIST_PREFIX = re.compile(r'^\s*(?:[-*•]|\d+[.)])\s*')


def _clean_candidate(raw: str) -> str:
    text = _LIST_PREFIX.sub("", raw.strip())
    text = text.strip().strip('",').strip()
    if text.startswith(("'", '"')) and text.endswith(("'", '"')) and len(text) > 1:
        text = text[1:-1].strip()
    return re.sub(r"\s+", " ", text)


def _as_string_list(parsed: Any) -> List[str]:
    if not isinstance(parsed, list):
        return []
    return [str(item) for item in parsed if isinstance(item, (str, int, float))]


def _extract_candidates(text: str) -> List[str]:
    """Pull query strings out of model output that may not be valid JSON."""
    match = _JSON_ARRAY.search(text)
    if match:
        try:
            candidates = _as_string_list(json.loads(match.group(0)))
            if candidates:
                return candidates
        except json.JSONDecodeError:
            pass

    # Truncated array (the model hit max_new_tokens): close it and retry.
    if "[" in text:
        fragment = text[text.index("["):].rstrip()
        for repaired in (fragment + "]", fragment.rstrip(",") + "]",
                         fragment.rsplit(",", 1)[0] + "]"):
            try:
                candidates = _as_string_list(json.loads(repaired))
                if candidates:
                    return candidates
            except json.JSONDecodeError:
                continue

    # Any quoted strings left over from a half-written array.
    quoted = re.findall(r'"([^"\n]{8,300})"', text)
    if quoted:
        return quoted

    # Last resort: numbered lists, bullets, bare questions.
    return [line for line in text.splitlines() if "?" in line]


def parse_queries(raw_output: str, max_queries: int) -> List[str]:
    """Extract queries from the model output, tolerating malformed JSON."""
    text = raw_output.strip()
    text = re.sub(r"^```(?:json)?|```$", "", text, flags=re.MULTILINE).strip()

    candidates = _extract_candidates(text)

    queries: List[str] = []
    seen = set()
    for candidate in candidates:
        query = _clean_candidate(candidate)
        if not query:
            continue
        if not query.endswith("?"):
            # Keep a trailing question if the model appended stray punctuation.
            if "?" in query:
                query = query[:query.rindex("?") + 1].strip()
            else:
                continue
        words = query.split()
        if not (4 <= len(words) <= 30):
            continue
        lowered = query.lower()
        if any(re.search(p, lowered) for p in BANNED_PATTERNS):
            continue
        if "{" in query or "}" in query:
            continue
        key = re.sub(r"[^\w]+", "", lowered)
        if key in seen:
            continue
        seen.add(key)
        queries.append(query)
        if len(queries) >= max_queries:
            break

    return queries


